/**
 * Dataset release artifacts, generated from the one source of truth
 * (dataset/v5/lineage_v5.json) so the CSV copies can never drift from it:
 *
 *   dataset/v5/lineage_v5_nodes.csv   one row per language or tool
 *   dataset/v5/lineage_v5_edges.csv   one row per cited relationship
 *   dataset/v5/DATACARD.md            data card (Hugging Face compatible front matter)
 *
 * `public/dataset` is a symlink to `dataset/`, so these are served at
 * /dataset/v5/… alongside the JSON. Logo fields are left out of the CSV on
 * purpose: logos carry their own third-party licenses, not CC BY 4.0.
 *
 * Run as part of `npm run seo:generate`.
 */
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'dataset/v5');
const SITE = 'https://www.languagelineage.org';

interface Node {
  id: string;
  name: string;
  first_release_year: number | null;
  current_primary_implementation_language: string;
  paradigm: string[];
  typing: string;
  runtime_model: string;
  self_hosting: boolean;
  garbage_collected: boolean | null;
  company: string | null;
  cluster_hint: string;
  notes: string;
}
interface Edge {
  from_language: string;
  to_language: string;
  relationship: string;
  start_year: number | null;
  end_year: number | null;
  confidence: number;
  evidence_source: string;
  notes: string;
}

const data = JSON.parse(readFileSync(join(DIR, 'lineage_v5.json'), 'utf8'));
const nodes: Node[] = data.languages;
const edges: Edge[] = data.relationships;
const nameOf = new Map(nodes.map((n) => [n.id, n.name]));

// RFC 4180: quote every field that contains a comma, quote, or line break; double inner quotes.
function csvField(value: unknown): string {
  if (value === null || value === undefined) return '';
  const s = Array.isArray(value) ? value.join(';') : String(value);
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

function toCsv(header: string[], rows: unknown[][]): string {
  return [header, ...rows].map((r) => r.map(csvField).join(',')).join('\r\n') + '\r\n';
}

const NODE_COLUMNS = [
  'id', 'name', 'kind', 'first_release_year', 'current_primary_implementation_language', 'paradigm',
  'typing', 'runtime_model', 'self_hosting', 'garbage_collected', 'company', 'cluster_hint', 'notes',
];
const nodeRows = nodes.map((n) => [
  n.id, n.name, n.id.startsWith('tool:') ? 'tool' : 'language', n.first_release_year,
  n.current_primary_implementation_language, n.paradigm, n.typing, n.runtime_model, n.self_hosting,
  n.garbage_collected, n.company, n.cluster_hint, n.notes,
]);

const EDGE_COLUMNS = [
  'from_id', 'from_name', 'to_id', 'to_name', 'relationship', 'start_year', 'end_year',
  'confidence', 'evidence_source', 'notes',
];
const edgeRows = edges.map((e) => [
  e.from_language, nameOf.get(e.from_language), e.to_language, nameOf.get(e.to_language), e.relationship,
  e.start_year, e.end_year, e.confidence, e.evidence_source, e.notes,
]);

writeFileSync(join(DIR, 'lineage_v5_nodes.csv'), toCsv(NODE_COLUMNS, nodeRows));
writeFileSync(join(DIR, 'lineage_v5_edges.csv'), toCsv(EDGE_COLUMNS, edgeRows));

// ---- Data card -------------------------------------------------------------

const count = <T>(xs: T[], key: (x: T) => string) =>
  [...xs.reduce((m, x) => m.set(key(x), (m.get(key(x)) ?? 0) + 1), new Map<string, number>())]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));

const host = (u: string) => { try { return new URL(u).hostname.replace(/^www\./, ''); } catch { return 'invalid'; } };
const wikipedia = edges.filter((e) => host(e.evidence_source).endsWith('wikipedia.org')).length;
const dated = edges.filter((e) => e.start_year != null).length;
const ended = edges.filter((e) => e.end_year != null).length;
const languages = nodes.filter((n) => n.id.startsWith('lang:')).length;
const tools = nodes.length - languages;
const confidences = edges.map((e) => e.confidence).sort((a, b) => a - b);
const pct = (n: number) => `${Math.round((n / edges.length) * 100)}%`;

const typeTable = count(edges, (e) => e.relationship).map(([t, n]) => `| \`${t}\` | ${n} |`).join('\n');
const hostTable = count(edges, (e) => host(e.evidence_source)).slice(0, 10)
  .map(([h, n]) => `| ${h} | ${n} |`).join('\n');

